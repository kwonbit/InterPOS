-- InterPOS operational foundation: shift opening/closing and cash control
-- Firebird 5.0 / UTF8
-- Run once after database/07_sales_closing.sql on an existing database.

ALTER TABLE POS_ORDER ADD EMPLOYEE_ID INTEGER;
ALTER TABLE POS_ORDER ADD TERMINAL_ID INTEGER;
ALTER TABLE POS_ORDER ADD DISCOUNT_AMOUNT NUMERIC(15,2) DEFAULT 0 NOT NULL;
ALTER TABLE POS_ORDER ADD SERVICE_AMOUNT NUMERIC(15,2) DEFAULT 0 NOT NULL;
ALTER TABLE POS_ORDER ADD ORDER_NOTE VARCHAR(500);
ALTER TABLE POS_ORDER ADD UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP;

ALTER TABLE POS_ORDER ADD CONSTRAINT FK_ORDER_EMPLOYEE
  FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEE(EMPLOYEE_ID);
ALTER TABLE POS_ORDER ADD CONSTRAINT FK_ORDER_TERMINAL
  FOREIGN KEY (TERMINAL_ID) REFERENCES POS_TERMINAL(TERMINAL_ID);

ALTER TABLE POS_PAYMENT ADD RECEIVED_AMOUNT NUMERIC(15,2) DEFAULT 0 NOT NULL;
ALTER TABLE POS_PAYMENT ADD CHANGE_AMOUNT NUMERIC(15,2) DEFAULT 0 NOT NULL;
ALTER TABLE POS_PAYMENT ADD PAYMENT_STATUS VARCHAR(20) DEFAULT 'APPROVED' NOT NULL;
ALTER TABLE POS_PAYMENT ADD APPROVAL_NO VARCHAR(50);
ALTER TABLE POS_PAYMENT ADD CARD_COMPANY VARCHAR(50);
ALTER TABLE POS_PAYMENT ADD INSTALLMENT_MONTH INTEGER DEFAULT 0 NOT NULL;
ALTER TABLE POS_PAYMENT ADD CANCELED_AT TIMESTAMP;

CREATE TABLE POS_SHIFT (
  SHIFT_ID BIGINT NOT NULL,
  STORE_ID INTEGER NOT NULL,
  TERMINAL_ID INTEGER NOT NULL,
  BUSINESS_DATE DATE NOT NULL,
  SHIFT_STATUS VARCHAR(12) DEFAULT 'OPEN' NOT NULL,
  OPENING_CASH NUMERIC(15,2) DEFAULT 0 NOT NULL,
  EXPECTED_CASH NUMERIC(15,2) DEFAULT 0 NOT NULL,
  COUNTED_CASH NUMERIC(15,2) DEFAULT 0 NOT NULL,
  CASH_DIFFERENCE NUMERIC(15,2) DEFAULT 0 NOT NULL,
  OPENED_BY INTEGER NOT NULL,
  OPENED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CLOSED_BY INTEGER,
  CLOSED_AT TIMESTAMP,
  CLOSE_NOTE VARCHAR(500),
  ACTIVE_TERMINAL_ID COMPUTED BY (
    CASE WHEN SHIFT_STATUS = 'OPEN' THEN TERMINAL_ID ELSE NULL END
  ),
  CONSTRAINT PK_POS_SHIFT PRIMARY KEY (SHIFT_ID),
  CONSTRAINT FK_SHIFT_STORE FOREIGN KEY (STORE_ID) REFERENCES STORE_INFO(STORE_ID),
  CONSTRAINT FK_SHIFT_TERMINAL FOREIGN KEY (TERMINAL_ID) REFERENCES POS_TERMINAL(TERMINAL_ID),
  CONSTRAINT FK_SHIFT_OPEN_EMP FOREIGN KEY (OPENED_BY) REFERENCES EMPLOYEE(EMPLOYEE_ID),
  CONSTRAINT FK_SHIFT_CLOSE_EMP FOREIGN KEY (CLOSED_BY) REFERENCES EMPLOYEE(EMPLOYEE_ID),
  CONSTRAINT CK_SHIFT_STATUS CHECK (SHIFT_STATUS IN ('OPEN', 'CLOSED'))
);

CREATE TABLE POS_CASH_MOVEMENT (
  CASH_MOVEMENT_ID BIGINT NOT NULL,
  SHIFT_ID BIGINT NOT NULL,
  MOVEMENT_TYPE VARCHAR(10) NOT NULL,
  REASON_CODE VARCHAR(30) NOT NULL,
  AMOUNT NUMERIC(15,2) NOT NULL,
  DESCRIPTION VARCHAR(250),
  EMPLOYEE_ID INTEGER NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_CASH_MOVEMENT PRIMARY KEY (CASH_MOVEMENT_ID),
  CONSTRAINT FK_CASH_MOVE_SHIFT FOREIGN KEY (SHIFT_ID) REFERENCES POS_SHIFT(SHIFT_ID),
  CONSTRAINT FK_CASH_MOVE_EMP FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEE(EMPLOYEE_ID),
  CONSTRAINT CK_CASH_MOVE_TYPE CHECK (MOVEMENT_TYPE IN ('IN', 'OUT')),
  CONSTRAINT CK_CASH_MOVE_AMOUNT CHECK (AMOUNT > 0)
);

CREATE SEQUENCE GEN_POS_SHIFT_ID;
CREATE SEQUENCE GEN_POS_CASH_MOVEMENT_ID;

EXECUTE BLOCK
AS
  DECLARE VARIABLE V_ID BIGINT;
BEGIN
  SELECT COALESCE(MAX(SHIFT_ID), 0) + 1 FROM POS_SHIFT INTO :V_ID;
  EXECUTE STATEMENT 'ALTER SEQUENCE GEN_POS_SHIFT_ID RESTART WITH ' || CAST(V_ID AS VARCHAR(20));
  SELECT COALESCE(MAX(CASH_MOVEMENT_ID), 0) + 1 FROM POS_CASH_MOVEMENT INTO :V_ID;
  EXECUTE STATEMENT 'ALTER SEQUENCE GEN_POS_CASH_MOVEMENT_ID RESTART WITH ' || CAST(V_ID AS VARCHAR(20));
END;

CREATE UNIQUE INDEX UX_SHIFT_ACTIVE_TERMINAL
  ON POS_SHIFT (STORE_ID, ACTIVE_TERMINAL_ID);
CREATE INDEX IX_SHIFT_STORE_DATE
  ON POS_SHIFT (STORE_ID, BUSINESS_DATE, SHIFT_STATUS);
CREATE INDEX IX_SHIFT_TERMINAL_STATUS
  ON POS_SHIFT (TERMINAL_ID, SHIFT_STATUS);
CREATE INDEX IX_CASH_MOVEMENT_SHIFT
  ON POS_CASH_MOVEMENT (SHIFT_ID, CREATED_AT);
CREATE INDEX IX_ORDER_EMPLOYEE_DATE
  ON POS_ORDER (STORE_ID, EMPLOYEE_ID, ORDERED_AT);
CREATE INDEX IX_PAYMENT_STATUS_DATE
  ON POS_PAYMENT (PAYMENT_STATUS, PAID_AT);
