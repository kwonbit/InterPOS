CREATE TABLE POS_SHIFT (
  SHIFT_ID BIGINT NOT NULL,
  STORE_ID INTEGER NOT NULL,
  TERMINAL_ID INTEGER NOT NULL,
  BUSINESS_DATE DATE NOT NULL,
  SHIFT_STATUS VARCHAR(12) DEFAULT 'OPEN' NOT NULL,
  OPENING_CASH NUMERIC(15,2) DEFAULT 0 NOT NULL,
  EXPECTED_CASH NUMERIC(15,2) DEFAULT 0 NOT NULL,
  COUNTED_CASH NUMERIC(15,2) DEFAULT 0 NOT NULL,
  CASH_DIFFERENCE NUMERIC(15,2) DEFAULT 0 NOT NULL,
  OPENED_BY INTEGER NOT NULL,
  OPENED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CLOSED_BY INTEGER,
  CLOSED_AT TIMESTAMP,
  CLOSE_NOTE VARCHAR(500),
  CONSTRAINT PK_POS_SHIFT PRIMARY KEY (SHIFT_ID),
  CONSTRAINT FK_SHIFT_STORE FOREIGN KEY (STORE_ID) REFERENCES STORE_INFO(STORE_ID),
  CONSTRAINT FK_SHIFT_TERMINAL FOREIGN KEY (TERMINAL_ID) REFERENCES POS_TERMINAL(TERMINAL_ID),
  CONSTRAINT FK_SHIFT_OPEN_EMP FOREIGN KEY (OPENED_BY) REFERENCES EMPLOYEE(EMPLOYEE_ID),
  CONSTRAINT FK_SHIFT_CLOSE_EMP FOREIGN KEY (CLOSED_BY) REFERENCES EMPLOYEE(EMPLOYEE_ID),
  CONSTRAINT CK_SHIFT_STATUS CHECK (SHIFT_STATUS IN ('OPEN', 'CLOSED'))
);

CREATE TABLE POS_CASH_MOVEMENT (
  CASH_MOVEMENT_ID BIGINT NOT NULL,
  SHIFT_ID BIGINT NOT NULL,
  MOVEMENT_TYPE VARCHAR(10) NOT NULL,
  REASON_CODE VARCHAR(30) NOT NULL,
  AMOUNT NUMERIC(15,2) NOT NULL,
  DESCRIPTION VARCHAR(250),
  EMPLOYEE_ID INTEGER NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_CASH_MOVEMENT PRIMARY KEY (CASH_MOVEMENT_ID),
  CONSTRAINT FK_CASH_MOVE_SHIFT FOREIGN KEY (SHIFT_ID) REFERENCES POS_SHIFT(SHIFT_ID),
  CONSTRAINT FK_CASH_MOVE_EMP FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEE(EMPLOYEE_ID),
  CONSTRAINT CK_CASH_MOVE_TYPE CHECK (MOVEMENT_TYPE IN ('IN', 'OUT')),
  CONSTRAINT CK_CASH_MOVE_AMOUNT CHECK (AMOUNT > 0)
);

-- Device definitions are data-driven; actual device protocols are implemented
-- by Delphi adapters after the printer/VAN models are confirmed.
CREATE TABLE POS_PRINTER_CONFIG (
  PRINTER_ID INTEGER NOT NULL,
  STORE_ID INTEGER NOT NULL,
  TERMINAL_ID INTEGER,
  PRINTER_NAME VARCHAR(80) NOT NULL,
  PRINTER_TYPE VARCHAR(15) NOT NULL,
  CONNECTION_TYPE VARCHAR(15) DEFAULT 'WINDOWS' NOT NULL,
  DEVICE_NAME VARCHAR(150),
  IP_ADDRESS VARCHAR(45),
  PORT_NO INTEGER,
  ACTIVE_YN CHAR(1) DEFAULT 'Y' NOT NULL,
  CONSTRAINT PK_POS_PRINTER PRIMARY KEY (PRINTER_ID),
  CONSTRAINT FK_PRINTER_STORE FOREIGN KEY (STORE_ID) REFERENCES STORE_INFO(STORE_ID),
  CONSTRAINT FK_PRINTER_TERMINAL FOREIGN KEY (TERMINAL_ID) REFERENCES POS_TERMINAL(TERMINAL_ID),
  CONSTRAINT CK_PRINTER_TYPE CHECK (PRINTER_TYPE IN ('RECEIPT', 'KITCHEN', 'CASH_DRAWER', 'REPORT'))
);

CREATE TABLE POS_KITCHEN_ROUTE (
  ROUTE_ID INTEGER NOT NULL,
  STORE_ID INTEGER NOT NULL,
  CATEGORY_ID INTEGER,
  MENU_ID INTEGER,
  PRINTER_ID INTEGER NOT NULL,
  ACTIVE_YN CHAR(1) DEFAULT 'Y' NOT NULL,
  CONSTRAINT PK_KITCHEN_ROUTE PRIMARY KEY (ROUTE_ID),
  CONSTRAINT FK_KROUTE_STORE FOREIGN KEY (STORE_ID) REFERENCES STORE_INFO(STORE_ID),
  CONSTRAINT FK_KROUTE_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES MENU_CATEGORY(CATEGORY_ID),
  CONSTRAINT FK_KROUTE_MENU FOREIGN KEY (MENU_ID) REFERENCES MENU_ITEM(MENU_ID),
  CONSTRAINT FK_KROUTE_PRINTER FOREIGN KEY (PRINTER_ID) REFERENCES POS_PRINTER_CONFIG(PRINTER_ID),
  CONSTRAINT CK_KROUTE_TARGET CHECK (
    (CATEGORY_ID IS NOT NULL AND MENU_ID IS NULL) OR
    (CATEGORY_ID IS NULL AND MENU_ID IS NOT NULL)
  )
);

CREATE TABLE POS_TOUCH_LAYOUT (
  LAYOUT_ID INTEGER NOT NULL,
  STORE_ID INTEGER NOT NULL,
  TERMINAL_ID INTEGER,
  LAYOUT_NAME VARCHAR(80) NOT NULL,
  SCREEN_MODE VARCHAR(12) DEFAULT 'DINE_IN' NOT NULL,
  ACTIVE_YN CHAR(1) DEFAULT 'Y' NOT NULL,
  CONSTRAINT PK_TOUCH_LAYOUT PRIMARY KEY (LAYOUT_ID),
  CONSTRAINT FK_TOUCH_LAYOUT_STORE FOREIGN KEY (STORE_ID) REFERENCES STORE_INFO(STORE_ID),
  CONSTRAINT FK_TOUCH_LAYOUT_TERMINAL FOREIGN KEY (TERMINAL_ID) REFERENCES POS_TERMINAL(TERMINAL_ID)
);

CREATE TABLE POS_TOUCH_KEY (
  TOUCH_KEY_ID INTEGER NOT NULL,
  LAYOUT_ID INTEGER NOT NULL,
  KEY_TYPE VARCHAR(12) NOT NULL,
  CATEGORY_ID INTEGER,
  MENU_ID INTEGER,
  KEY_CAPTION VARCHAR(60),
  GRID_X SMALLINT DEFAULT 0 NOT NULL,
  GRID_Y SMALLINT DEFAULT 0 NOT NULL,
  GRID_W SMALLINT DEFAULT 1 NOT NULL,
  GRID_H SMALLINT DEFAULT 1 NOT NULL,
  BACK_COLOR INTEGER,
  TEXT_COLOR INTEGER,
  DISPLAY_ORDER INTEGER DEFAULT 0 NOT NULL,
  CONSTRAINT PK_TOUCH_KEY PRIMARY KEY (TOUCH_KEY_ID),
  CONSTRAINT FK_TOUCH_KEY_LAYOUT FOREIGN KEY (LAYOUT_ID) REFERENCES POS_TOUCH_LAYOUT(LAYOUT_ID),
  CONSTRAINT FK_TOUCH_KEY_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES MENU_CATEGORY(CATEGORY_ID),
  CONSTRAINT FK_TOUCH_KEY_MENU FOREIGN KEY (MENU_ID) REFERENCES MENU_ITEM(MENU_ID),
  CONSTRAINT CK_TOUCH_KEY_TYPE CHECK (KEY_TYPE IN ('CATEGORY', 'MENU', 'FUNCTION'))
);

CREATE TABLE POS_SYSTEM_CONFIG (
  CONFIG_ID BIGINT NOT NULL,
  STORE_ID INTEGER NOT NULL,
  TERMINAL_ID INTEGER,
  CONFIG_KEY VARCHAR(80) NOT NULL,
  CONFIG_VALUE VARCHAR(1000),
  UPDATED_BY INTEGER,
  UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_SYSTEM_CONFIG PRIMARY KEY (CONFIG_ID),
  CONSTRAINT FK_SYS_CONFIG_STORE FOREIGN KEY (STORE_ID) REFERENCES STORE_INFO(STORE_ID),
  CONSTRAINT FK_SYS_CONFIG_TERMINAL FOREIGN KEY (TERMINAL_ID) REFERENCES POS_TERMINAL(TERMINAL_ID),
  CONSTRAINT FK_SYS_CONFIG_EMP FOREIGN KEY (UPDATED_BY) REFERENCES EMPLOYEE(EMPLOYEE_ID)
);

CREATE TABLE POS_AUDIT_LOG (
  AUDIT_ID BIGINT NOT NULL,
  STORE_ID INTEGER NOT NULL,
  TERMINAL_ID INTEGER,
  EMPLOYEE_ID INTEGER,
  ACTION_CODE VARCHAR(40) NOT NULL,
  ENTITY_NAME VARCHAR(40) NOT NULL,
  ENTITY_ID VARCHAR(40),
  BEFORE_VALUE BLOB SUB_TYPE TEXT,
  AFTER_VALUE BLOB SUB_TYPE TEXT,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_POS_AUDIT_LOG PRIMARY KEY (AUDIT_ID),
  CONSTRAINT FK_AUDIT_STORE FOREIGN KEY (STORE_ID) REFERENCES STORE_INFO(STORE_ID),
  CONSTRAINT FK_AUDIT_TERMINAL FOREIGN KEY (TERMINAL_ID) REFERENCES POS_TERMINAL(TERMINAL_ID),
  CONSTRAINT FK_AUDIT_EMP FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEE(EMPLOYEE_ID)
);

CREATE SEQUENCE GEN_POS_SHIFT_ID;
CREATE SEQUENCE GEN_POS_CASH_MOVEMENT_ID;
CREATE SEQUENCE GEN_POS_PRINTER_ID;
CREATE SEQUENCE GEN_POS_KITCHEN_ROUTE_ID;
CREATE SEQUENCE GEN_POS_TOUCH_LAYOUT_ID;
CREATE SEQUENCE GEN_POS_TOUCH_KEY_ID;
CREATE SEQUENCE GEN_POS_SYSTEM_CONFIG_ID;
CREATE SEQUENCE GEN_POS_AUDIT_ID;

EXECUTE BLOCK
AS
  DECLARE VARIABLE V_ID BIGINT;
BEGIN
  SELECT COALESCE(MAX(SHIFT_ID), 0) + 1 FROM POS_SHIFT INTO :V_ID;
  EXECUTE STATEMENT 'ALTER SEQUENCE GEN_POS_SHIFT_ID RESTART WITH ' || CAST(V_ID AS VARCHAR(20));
  SELECT COALESCE(MAX(CASH_MOVEMENT_ID), 0) + 1 FROM POS_CASH_MOVEMENT INTO :V_ID;
  EXECUTE STATEMENT 'ALTER SEQUENCE GEN_POS_CASH_MOVEMENT_ID RESTART WITH ' || CAST(V_ID AS VARCHAR(20));
  SELECT COALESCE(MAX(PRINTER_ID), 0) + 1 FROM POS_PRINTER_CONFIG INTO :V_ID;
  EXECUTE STATEMENT 'ALTER SEQUENCE GEN_POS_PRINTER_ID RESTART WITH ' || CAST(V_ID AS VARCHAR(20));
  SELECT COALESCE(MAX(ROUTE_ID), 0) + 1 FROM POS_KITCHEN_ROUTE INTO :V_ID;
  EXECUTE STATEMENT 'ALTER SEQUENCE GEN_POS_KITCHEN_ROUTE_ID RESTART WITH ' || CAST(V_ID AS VARCHAR(20));
  SELECT COALESCE(MAX(LAYOUT_ID), 0) + 1 FROM POS_TOUCH_LAYOUT INTO :V_ID;
  EXECUTE STATEMENT 'ALTER SEQUENCE GEN_POS_TOUCH_LAYOUT_ID RESTART WITH ' || CAST(V_ID AS VARCHAR(20));
  SELECT COALESCE(MAX(TOUCH_KEY_ID), 0) + 1 FROM POS_TOUCH_KEY INTO :V_ID;
  EXECUTE STATEMENT 'ALTER SEQUENCE GEN_POS_TOUCH_KEY_ID RESTART WITH ' || CAST(V_ID AS VARCHAR(20));
  SELECT COALESCE(MAX(CONFIG_ID), 0) + 1 FROM POS_SYSTEM_CONFIG INTO :V_ID;
  EXECUTE STATEMENT 'ALTER SEQUENCE GEN_POS_SYSTEM_CONFIG_ID RESTART WITH ' || CAST(V_ID AS VARCHAR(20));
  SELECT COALESCE(MAX(AUDIT_ID), 0) + 1 FROM POS_AUDIT_LOG INTO :V_ID;
  EXECUTE STATEMENT 'ALTER SEQUENCE GEN_POS_AUDIT_ID RESTART WITH ' || CAST(V_ID AS VARCHAR(20));
END;

