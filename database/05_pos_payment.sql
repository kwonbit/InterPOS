-- InterPOS POS payment sequence for Firebird 5.0
-- Run once after 04_pos_sales.sql.

CREATE SEQUENCE GEN_POS_PAYMENT_ID;

EXECUTE BLOCK
AS
  DECLARE VARIABLE V_ID BIGINT;
BEGIN
  SELECT COALESCE(MAX(PAYMENT_ID), 0) + 1
    FROM POS_PAYMENT
    INTO :V_ID;
  EXECUTE STATEMENT 'ALTER SEQUENCE GEN_POS_PAYMENT_ID RESTART WITH ' ||
    CAST(V_ID AS VARCHAR(20));
END;
