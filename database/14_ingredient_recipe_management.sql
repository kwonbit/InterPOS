-- InterPOS ingredient inventory and menu recipe foundation
-- Firebird 5.0 / UTF8
-- Run once after database/13_operating_expenses.sql.
-- Do not execute this migration more than once.

CREATE TABLE POS_INGREDIENT (
  INGREDIENT_ID BIGINT NOT NULL,
  STORE_ID INTEGER NOT NULL,
  INGREDIENT_NAME VARCHAR(120) NOT NULL,
  UNIT_CODE VARCHAR(20) NOT NULL,
  STOCK_QTY NUMERIC(15,3) DEFAULT 0 NOT NULL,
  LOW_STOCK_QTY NUMERIC(15,3) DEFAULT 0 NOT NULL,
  AVG_UNIT_COST NUMERIC(15,4) DEFAULT 0 NOT NULL,
  ACTIVE_YN CHAR(1) DEFAULT 'Y' NOT NULL,
  CREATED_BY INTEGER NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP,
  CONSTRAINT PK_POS_INGREDIENT PRIMARY KEY (INGREDIENT_ID),
  CONSTRAINT FK_POS_ING_STORE FOREIGN KEY (STORE_ID) REFERENCES STORE_INFO(STORE_ID),
  CONSTRAINT FK_POS_ING_CREATED FOREIGN KEY (CREATED_BY) REFERENCES EMPLOYEE(EMPLOYEE_ID),
  CONSTRAINT CK_POS_ING_STOCK CHECK (STOCK_QTY >= 0),
  CONSTRAINT CK_POS_ING_LOW CHECK (LOW_STOCK_QTY >= 0),
  CONSTRAINT CK_POS_ING_COST CHECK (AVG_UNIT_COST >= 0),
  CONSTRAINT CK_POS_ING_ACTIVE CHECK (ACTIVE_YN IN ('Y', 'N'))
);

CREATE SEQUENCE GEN_POS_INGREDIENT_ID;
EXECUTE BLOCK
AS
  DECLARE VARIABLE V_ID BIGINT;
BEGIN
  SELECT COALESCE(MAX(INGREDIENT_ID), 0) + 1 FROM POS_INGREDIENT INTO :V_ID;
  EXECUTE STATEMENT 'ALTER SEQUENCE GEN_POS_INGREDIENT_ID RESTART WITH ' || CAST(V_ID AS VARCHAR(20));
END;

CREATE TABLE POS_MENU_RECIPE (
  RECIPE_ID BIGINT NOT NULL,
  STORE_ID INTEGER NOT NULL,
  MENU_ID INTEGER NOT NULL,
  INGREDIENT_ID BIGINT NOT NULL,
  QUANTITY NUMERIC(15,4) NOT NULL,
  CREATED_BY INTEGER NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_POS_MENU_RECIPE PRIMARY KEY (RECIPE_ID),
  CONSTRAINT FK_POS_RECIPE_STORE FOREIGN KEY (STORE_ID) REFERENCES STORE_INFO(STORE_ID),
  CONSTRAINT FK_POS_RECIPE_MENU FOREIGN KEY (MENU_ID) REFERENCES MENU_ITEM(MENU_ID),
  CONSTRAINT FK_POS_RECIPE_ING FOREIGN KEY (INGREDIENT_ID) REFERENCES POS_INGREDIENT(INGREDIENT_ID),
  CONSTRAINT FK_POS_RECIPE_EMP FOREIGN KEY (CREATED_BY) REFERENCES EMPLOYEE(EMPLOYEE_ID),
  CONSTRAINT CK_POS_RECIPE_QTY CHECK (QUANTITY > 0),
  CONSTRAINT UQ_POS_RECIPE_ITEM UNIQUE (STORE_ID, MENU_ID, INGREDIENT_ID)
);

CREATE SEQUENCE GEN_POS_MENU_RECIPE_ID;
EXECUTE BLOCK
AS
