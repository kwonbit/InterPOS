  EXECUTE STATEMENT 'ALTER SEQUENCE GEN_POS_MENU_RECIPE_ID RESTART WITH ' || CAST(V_ID AS VARCHAR(20));
END;

CREATE TABLE POS_INGREDIENT_MOVEMENT (
  MOVEMENT_ID BIGINT NOT NULL,
  STORE_ID INTEGER NOT NULL,
  INGREDIENT_ID BIGINT NOT NULL,
  MOVEMENT_TYPE VARCHAR(12) NOT NULL,
  QUANTITY NUMERIC(15,3) NOT NULL,
  STOCK_BEFORE NUMERIC(15,3) NOT NULL,
  STOCK_AFTER NUMERIC(15,3) NOT NULL,
  UNIT_COST NUMERIC(15,4) DEFAULT 0 NOT NULL,
  REFERENCE_TYPE VARCHAR(20),
  REFERENCE_ID BIGINT,
  DESCRIPTION VARCHAR(250),
  EMPLOYEE_ID INTEGER NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_POS_ING_MOVEMENT PRIMARY KEY (MOVEMENT_ID),
  CONSTRAINT FK_POS_ING_MOV_STORE FOREIGN KEY (STORE_ID) REFERENCES STORE_INFO(STORE_ID),
  CONSTRAINT FK_POS_ING_MOV_ING FOREIGN KEY (INGREDIENT_ID) REFERENCES POS_INGREDIENT(INGREDIENT_ID),
  CONSTRAINT FK_POS_ING_MOV_EMP FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEE(EMPLOYEE_ID),
  CONSTRAINT CK_POS_ING_MOV_TYPE CHECK (MOVEMENT_TYPE IN ('IN', 'OUT', 'ADJUST')),
  CONSTRAINT CK_POS_ING_MOV_QTY CHECK (QUANTITY > 0),
  CONSTRAINT CK_POS_ING_MOV_STOCK CHECK (STOCK_BEFORE >= 0 AND STOCK_AFTER >= 0),
  CONSTRAINT CK_POS_ING_MOV_COST CHECK (UNIT_COST >= 0)
);

CREATE SEQUENCE GEN_POS_INGREDIENT_MOVEMENT_ID;
EXECUTE BLOCK
AS
  DECLARE VARIABLE V_ID BIGINT;
BEGIN
  SELECT COALESCE(MAX(MOVEMENT_ID), 0) + 1 FROM POS_INGREDIENT_MOVEMENT INTO :V_ID;
  EXECUTE STATEMENT 'ALTER SEQUENCE GEN_POS_INGREDIENT_MOVEMENT_ID RESTART WITH ' || CAST(V_ID AS VARCHAR(20));
END;

CREATE INDEX IX_POS_ING_STORE_NAME ON POS_INGREDIENT (STORE_ID, ACTIVE_YN, INGREDIENT_NAME);
CREATE INDEX IX_POS_RECIPE_MENU ON POS_MENU_RECIPE (STORE_ID, MENU_ID);
CREATE INDEX IX_POS_RECIPE_ING ON POS_MENU_RECIPE (STORE_ID, INGREDIENT_ID);
CREATE INDEX IX_POS_ING_MOV_DATE ON POS_INGREDIENT_MOVEMENT (STORE_ID, INGREDIENT_ID, CREATED_AT);
