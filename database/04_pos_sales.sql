ALTER TABLE POS_ORDER_ITEM ADD OPTION_TEXT VARCHAR(500);
ALTER TABLE POS_ORDER_ITEM ADD OPTION_AMOUNT NUMERIC(15,2) DEFAULT 0 NOT NULL;

CREATE SEQUENCE GEN_POS_ORDER_ID;
CREATE SEQUENCE GEN_POS_ORDER_ITEM_ID;

EXECUTE BLOCK
AS
  DECLARE VARIABLE V_ID BIGINT;
BEGIN
  SELECT COALESCE(MAX(ORDER_ID), 0) + 1 FROM POS_ORDER INTO :V_ID;
  EXECUTE STATEMENT 'ALTER SEQUENCE GEN_POS_ORDER_ID RESTART WITH ' || CAST(V_ID AS VARCHAR(20));

  SELECT COALESCE(MAX(ORDER_ITEM_ID), 0) + 1 FROM POS_ORDER_ITEM INTO :V_ID;
  EXECUTE STATEMENT 'ALTER SEQUENCE GEN_POS_ORDER_ITEM_ID RESTART WITH ' || CAST(V_ID AS VARCHAR(20));
END;

CREATE INDEX IX_ORDER_TABLE_STATUS ON POS_ORDER (STORE_ID, TABLE_ID, ORDER_STATUS);
CREATE INDEX IX_MENU_ACTIVE_CATEGORY ON MENU_ITEM (STORE_ID, CATEGORY_ID, ACTIVE_YN);
