-- InterPOS operating expense management
-- Firebird 5.0 / UTF8
-- Run once after database/12_supplier_payables.sql.
-- Do not execute this migration more than once.

CREATE TABLE POS_OPERATING_EXPENSE (
  EXPENSE_ID BIGINT NOT NULL,
  STORE_ID INTEGER NOT NULL,
  EXPENSE_DATE DATE NOT NULL,
  CATEGORY VARCHAR(60) NOT NULL,
  DESCRIPTION VARCHAR(250) NOT NULL,
  AMOUNT NUMERIC(15,2) NOT NULL,
  PAYMENT_METHOD VARCHAR(20) NOT NULL,
  NOTE VARCHAR(500),
  EXPENSE_STATUS VARCHAR(10) DEFAULT 'ACTIVE' NOT NULL,
  CREATED_BY INTEGER NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  VOIDED_BY INTEGER,
  VOIDED_AT TIMESTAMP,
  CONSTRAINT PK_POS_OPERATING_EXPENSE PRIMARY KEY (EXPENSE_ID),
  CONSTRAINT FK_POS_EXPENSE_STORE FOREIGN KEY (STORE_ID) REFERENCES STORE_INFO(STORE_ID),
  CONSTRAINT FK_POS_EXPENSE_CREATED FOREIGN KEY (CREATED_BY) REFERENCES EMPLOYEE(EMPLOYEE_ID),
  CONSTRAINT FK_POS_EXPENSE_VOIDED FOREIGN KEY (VOIDED_BY) REFERENCES EMPLOYEE(EMPLOYEE_ID),
  CONSTRAINT CK_POS_EXPENSE_AMOUNT CHECK (AMOUNT > 0),
  CONSTRAINT CK_POS_EXPENSE_METHOD CHECK (PAYMENT_METHOD IN ('CASH', 'BANK', 'CARD', 'OTHER')),
  CONSTRAINT CK_POS_EXPENSE_STATUS CHECK (EXPENSE_STATUS IN ('ACTIVE', 'VOID'))
);

CREATE SEQUENCE GEN_POS_OPERATING_EXPENSE_ID;

EXECUTE BLOCK
AS
  DECLARE VARIABLE V_ID BIGINT;
BEGIN
  SELECT COALESCE(MAX(EXPENSE_ID), 0) + 1
    FROM POS_OPERATING_EXPENSE INTO :V_ID;
  EXECUTE STATEMENT 'ALTER SEQUENCE GEN_POS_OPERATING_EXPENSE_ID RESTART WITH ' ||
    CAST(V_ID AS VARCHAR(20));
END;

CREATE INDEX IX_POS_EXPENSE_STORE_DATE
  ON POS_OPERATING_EXPENSE (STORE_ID, EXPENSE_DATE, EXPENSE_STATUS);
CREATE INDEX IX_POS_EXPENSE_CATEGORY
  ON POS_OPERATING_EXPENSE (STORE_ID, CATEGORY, EXPENSE_DATE);
