-- InterPOS / Firebird 5.0
-- Initial schema baseline. Execute in an empty InterPOS database.

CREATE TABLE STORE_INFO (
  STORE_ID INTEGER NOT NULL,
  STORE_NAME VARCHAR(100) NOT NULL,
  BUSINESS_NO VARCHAR(20),
  TEL VARCHAR(30),
  ADDRESS VARCHAR(250),
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_STORE_INFO PRIMARY KEY (STORE_ID)
);

CREATE TABLE POS_TERMINAL (
  TERMINAL_ID INTEGER NOT NULL,
  TERMINAL_NAME VARCHAR(50) NOT NULL,
  STORE_ID INTEGER NOT NULL,
  ACTIVE_YN CHAR(1) DEFAULT 'Y' NOT NULL,
  CONSTRAINT PK_POS_TERMINAL PRIMARY KEY (TERMINAL_ID),
  CONSTRAINT FK_TERMINAL_STORE FOREIGN KEY (STORE_ID) REFERENCES STORE_INFO(STORE_ID)
);

CREATE TABLE POS_TABLE (
  TABLE_ID INTEGER NOT NULL,
  STORE_ID INTEGER NOT NULL,
  TABLE_NAME VARCHAR(30) NOT NULL,
  TABLE_GROUP VARCHAR(30),
  DISPLAY_ORDER INTEGER DEFAULT 0 NOT NULL,
  ACTIVE_YN CHAR(1) DEFAULT 'Y' NOT NULL,
  CONSTRAINT PK_POS_TABLE PRIMARY KEY (TABLE_ID),
  CONSTRAINT FK_TABLE_STORE FOREIGN KEY (STORE_ID) REFERENCES STORE_INFO(STORE_ID)
);

CREATE TABLE MENU_CATEGORY (
  CATEGORY_ID INTEGER NOT NULL,
  STORE_ID INTEGER NOT NULL,
  CATEGORY_NAME VARCHAR(80) NOT NULL,
  DISPLAY_ORDER INTEGER DEFAULT 0 NOT NULL,
  ACTIVE_YN CHAR(1) DEFAULT 'Y' NOT NULL,
  CONSTRAINT PK_MENU_CATEGORY PRIMARY KEY (CATEGORY_ID),
  CONSTRAINT FK_CATEGORY_STORE FOREIGN KEY (STORE_ID) REFERENCES STORE_INFO(STORE_ID)
);

CREATE TABLE MENU_ITEM (
  MENU_ID INTEGER NOT NULL,
  STORE_ID INTEGER NOT NULL,
  CATEGORY_ID INTEGER NOT NULL,
  MENU_NAME VARCHAR(120) NOT NULL,
  PRICE NUMERIC(15,2) DEFAULT 0 NOT NULL,
  TAX_TYPE VARCHAR(10) DEFAULT 'TAX',
  ACTIVE_YN CHAR(1) DEFAULT 'Y' NOT NULL,
  CONSTRAINT PK_MENU_ITEM PRIMARY KEY (MENU_ID),
  CONSTRAINT FK_MENU_STORE FOREIGN KEY (STORE_ID) REFERENCES STORE_INFO(STORE_ID),
  CONSTRAINT FK_MENU_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES MENU_CATEGORY(CATEGORY_ID)
);

CREATE TABLE POS_ORDER (
  ORDER_ID BIGINT NOT NULL,
  STORE_ID INTEGER NOT NULL,
  TABLE_ID INTEGER,
  ORDER_NO VARCHAR(30) NOT NULL,
  ORDER_TYPE VARCHAR(15) DEFAULT 'DINE_IN' NOT NULL,
  ORDER_STATUS VARCHAR(20) DEFAULT 'OPEN' NOT NULL,
  ORDERED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  TOTAL_AMOUNT NUMERIC(15,2) DEFAULT 0 NOT NULL,
  CONSTRAINT PK_POS_ORDER PRIMARY KEY (ORDER_ID),
  CONSTRAINT FK_ORDER_STORE FOREIGN KEY (STORE_ID) REFERENCES STORE_INFO(STORE_ID),
  CONSTRAINT FK_ORDER_TABLE FOREIGN KEY (TABLE_ID) REFERENCES POS_TABLE(TABLE_ID)
);

CREATE TABLE POS_ORDER_ITEM (
  ORDER_ITEM_ID BIGINT NOT NULL,
  ORDER_ID BIGINT NOT NULL,
  MENU_ID INTEGER NOT NULL,
  MENU_NAME VARCHAR(120) NOT NULL,
  UNIT_PRICE NUMERIC(15,2) NOT NULL,
  QUANTITY NUMERIC(12,3) DEFAULT 1 NOT NULL,
  LINE_AMOUNT NUMERIC(15,2) NOT NULL,
  CONSTRAINT PK_ORDER_ITEM PRIMARY KEY (ORDER_ITEM_ID),
  CONSTRAINT FK_ORDER_ITEM_ORDER FOREIGN KEY (ORDER_ID) REFERENCES POS_ORDER(ORDER_ID),
  CONSTRAINT FK_ORDER_ITEM_MENU FOREIGN KEY (MENU_ID) REFERENCES MENU_ITEM(MENU_ID)
);

CREATE TABLE POS_PAYMENT (
  PAYMENT_ID BIGINT NOT NULL,
  ORDER_ID BIGINT NOT NULL,
  PAYMENT_METHOD VARCHAR(20) NOT NULL,
  PAYMENT_AMOUNT NUMERIC(15,2) NOT NULL,
  PAID_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_POS_PAYMENT PRIMARY KEY (PAYMENT_ID),
  CONSTRAINT FK_PAYMENT_ORDER FOREIGN KEY (ORDER_ID) REFERENCES POS_ORDER(ORDER_ID)
);

CREATE TABLE EMPLOYEE (
  EMPLOYEE_ID INTEGER NOT NULL,
  STORE_ID INTEGER NOT NULL,
  EMPLOYEE_NAME VARCHAR(60) NOT NULL,
  LOGIN_ID VARCHAR(40) NOT NULL,
  PASSWORD_HASH VARCHAR(255),
  ROLE_CODE VARCHAR(20) DEFAULT 'STAFF' NOT NULL,
  ACTIVE_YN CHAR(1) DEFAULT 'Y' NOT NULL,
  CONSTRAINT PK_EMPLOYEE PRIMARY KEY (EMPLOYEE_ID),
  CONSTRAINT FK_EMPLOYEE_STORE FOREIGN KEY (STORE_ID) REFERENCES STORE_INFO(STORE_ID)
);

CREATE INDEX IX_ORDER_DATE ON POS_ORDER (STORE_ID, ORDERED_AT);
CREATE INDEX IX_ORDER_STATUS ON POS_ORDER (STORE_ID, ORDER_STATUS);
CREATE INDEX IX_ORDER_ITEM_ORDER ON POS_ORDER_ITEM (ORDER_ID);
CREATE INDEX IX_PAYMENT_ORDER ON POS_PAYMENT (ORDER_ID);
