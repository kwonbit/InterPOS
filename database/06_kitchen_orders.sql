-- InterPOS kitchen ticket workflow for Firebird 5.0
-- Run once after 05_pos_payment.sql.

CREATE TABLE POS_KITCHEN_TICKET (
  KITCHEN_TICKET_ID BIGINT NOT NULL,
  ORDER_ID BIGINT NOT NULL,
  TICKET_NO VARCHAR(40) NOT NULL,
  STATUS VARCHAR(20) DEFAULT 'NEW' NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_POS_KITCHEN_TICKET PRIMARY KEY (KITCHEN_TICKET_ID),
  CONSTRAINT FK_KITCHEN_TICKET_ORDER FOREIGN KEY (ORDER_ID)
    REFERENCES POS_ORDER(ORDER_ID)
);

ALTER TABLE POS_ORDER_ITEM ADD KITCHEN_TICKET_ID BIGINT;
ALTER TABLE POS_ORDER_ITEM ADD CONSTRAINT FK_ORDER_ITEM_KITCHEN_TICKET
  FOREIGN KEY (KITCHEN_TICKET_ID) REFERENCES POS_KITCHEN_TICKET(KITCHEN_TICKET_ID);

CREATE SEQUENCE GEN_POS_KITCHEN_TICKET_ID;

EXECUTE BLOCK
AS
  DECLARE VARIABLE V_ID BIGINT;
BEGIN
  SELECT COALESCE(MAX(KITCHEN_TICKET_ID), 0) + 1
    FROM POS_KITCHEN_TICKET INTO :V_ID;
  EXECUTE STATEMENT 'ALTER SEQUENCE GEN_POS_KITCHEN_TICKET_ID RESTART WITH ' ||
    CAST(V_ID AS VARCHAR(20));
END;

CREATE INDEX IX_KITCHEN_TICKET_ORDER ON POS_KITCHEN_TICKET (ORDER_ID, CREATED_AT);
CREATE INDEX IX_KITCHEN_TICKET_STATUS ON POS_KITCHEN_TICKET (STATUS, CREATED_AT);
CREATE INDEX IX_ORDER_ITEM_KITCHEN_TICKET ON POS_ORDER_ITEM (KITCHEN_TICKET_ID);
