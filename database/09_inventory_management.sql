-- InterPOS inventory management extension
-- Firebird 5.0 / UTF8
-- Run once after database/08_operational_foundation.sql.
-- Do not execute this migration more than once.

ALTER TABLE MENU_ITEM ADD STOCK_MANAGED_YN CHAR(1) DEFAULT 'N' NOT NULL;
ALTER TABLE MENU_ITEM ADD STOCK_QTY NUMERIC(15,3) DEFAULT 0 NOT NULL;
ALTER TABLE MENU_ITEM ADD LOW_STOCK_QTY NUMERIC(15,3) DEFAULT 0 NOT NULL;

ALTER TABLE MENU_ITEM ADD CONSTRAINT CK_MENU_STOCK_QTY
  CHECK (STOCK_QTY >= 0);
ALTER TABLE MENU_ITEM ADD CONSTRAINT CK_MENU_LOW_STOCK_QTY
  CHECK (LOW_STOCK_QTY >= 0);
ALTER TABLE MENU_ITEM ADD CONSTRAINT CK_MENU_STOCK_MANAGED
  CHECK (STOCK_MANAGED_YN IN ('Y', 'N'));

CREATE TABLE POS_STOCK_MOVEMENT (
  STOCK_MOVEMENT_ID BIGINT NOT NULL,
  STORE_ID INTEGER NOT NULL,
  MENU_ID INTEGER NOT NULL,
  MOVEMENT_TYPE VARCHAR(10) NOT NULL,
  QUANTITY NUMERIC(15,3) NOT NULL,
  STOCK_BEFORE NUMERIC(15,3) NOT NULL,
  STOCK_AFTER NUMERIC(15,3) NOT NULL,
  REASON_CODE VARCHAR(30) NOT NULL,
  DESCRIPTION VARCHAR(250),
  REFERENCE_TYPE VARCHAR(20),
  REFERENCE_ID BIGINT,
  EMPLOYEE_ID INTEGER NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_POS_STOCK_MOVEMENT PRIMARY KEY (STOCK_MOVEMENT_ID),
  CONSTRAINT FK_STOCK_MOVE_STORE FOREIGN KEY (STORE_ID) REFERENCES STORE_INFO(STORE_ID),
  CONSTRAINT FK_STOCK_MOVE_MENU FOREIGN KEY (MENU_ID) REFERENCES MENU_ITEM(MENU_ID),
  CONSTRAINT FK_STOCK_MOVE_EMP FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEE(EMPLOYEE_ID),
  CONSTRAINT CK_STOCK_MOVE_TYPE CHECK (MOVEMENT_TYPE IN ('IN', 'OUT', 'ADJUST')),
  CONSTRAINT CK_STOCK_MOVE_QTY CHECK (QUANTITY > 0),
  CONSTRAINT CK_STOCK_MOVE_STOCK CHECK (STOCK_BEFORE >= 0 AND STOCK_AFTER >= 0)
);

CREATE SEQUENCE GEN_POS_STOCK_MOVEMENT_ID;

EXECUTE BLOCK
AS
  DECLARE VARIABLE V_ID BIGINT;
BEGIN
  SELECT COALESCE(MAX(STOCK_MOVEMENT_ID), 0) + 1
    FROM POS_STOCK_MOVEMENT INTO :V_ID;
  EXECUTE STATEMENT 'ALTER SEQUENCE GEN_POS_STOCK_MOVEMENT_ID RESTART WITH ' ||
    CAST(V_ID AS VARCHAR(20));
END;

CREATE INDEX IX_STOCK_MENU_DATE
  ON POS_STOCK_MOVEMENT (STORE_ID, MENU_ID, CREATED_AT);
CREATE INDEX IX_STOCK_STORE_DATE
  ON POS_STOCK_MOVEMENT (STORE_ID, CREATED_AT);
CREATE INDEX IX_MENU_STOCK_ALERT
  ON MENU_ITEM (STORE_ID, STOCK_MANAGED_YN, STOCK_QTY, LOW_STOCK_QTY);
