-- InterPOS daily sales closing for Firebird 5.0
-- Run once after 06_kitchen_orders.sql.

CREATE TABLE POS_SALES_CLOSE (
  CLOSE_ID BIGINT NOT NULL,
  STORE_ID INTEGER NOT NULL,
  BUSINESS_DATE DATE NOT NULL,
  ORDER_COUNT INTEGER DEFAULT 0 NOT NULL,
  TOTAL_AMOUNT NUMERIC(15,2) DEFAULT 0 NOT NULL,
  CASH_AMOUNT NUMERIC(15,2) DEFAULT 0 NOT NULL,
  CARD_AMOUNT NUMERIC(15,2) DEFAULT 0 NOT NULL,
  CLOSED_BY INTEGER,
  CLOSED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CLOSE_NOTE VARCHAR(500),
  CONSTRAINT PK_POS_SALES_CLOSE PRIMARY KEY (CLOSE_ID),
  CONSTRAINT FK_SALES_CLOSE_STORE FOREIGN KEY (STORE_ID) REFERENCES STORE_INFO(STORE_ID),
  CONSTRAINT FK_SALES_CLOSE_EMP FOREIGN KEY (CLOSED_BY) REFERENCES EMPLOYEE(EMPLOYEE_ID)
);

CREATE TABLE POS_SALES_CLOSE_MENU (
  CLOSE_MENU_ID BIGINT NOT NULL,
  CLOSE_ID BIGINT NOT NULL,
  MENU_NAME VARCHAR(120) NOT NULL,
  SOLD_QUANTITY NUMERIC(15,3) DEFAULT 0 NOT NULL,
  SALES_AMOUNT NUMERIC(15,2) DEFAULT 0 NOT NULL,
  CONSTRAINT PK_SALES_CLOSE_MENU PRIMARY KEY (CLOSE_MENU_ID),
  CONSTRAINT FK_CLOSE_MENU_CLOSE FOREIGN KEY (CLOSE_ID) REFERENCES POS_SALES_CLOSE(CLOSE_ID)
);

CREATE SEQUENCE GEN_POS_SALES_CLOSE_ID;
CREATE SEQUENCE GEN_POS_SALES_CLOSE_MENU_ID;

EXECUTE BLOCK
AS
  DECLARE VARIABLE V_ID BIGINT;
BEGIN
  SELECT COALESCE(MAX(CLOSE_ID), 0) + 1 FROM POS_SALES_CLOSE INTO :V_ID;
  EXECUTE STATEMENT 'ALTER SEQUENCE GEN_POS_SALES_CLOSE_ID RESTART WITH ' || CAST(V_ID AS VARCHAR(20));
  SELECT COALESCE(MAX(CLOSE_MENU_ID), 0) + 1 FROM POS_SALES_CLOSE_MENU INTO :V_ID;
  EXECUTE STATEMENT 'ALTER SEQUENCE GEN_POS_SALES_CLOSE_MENU_ID RESTART WITH ' || CAST(V_ID AS VARCHAR(20));
END;

CREATE UNIQUE INDEX UX_SALES_CLOSE_STORE_DATE ON POS_SALES_CLOSE (STORE_ID, BUSINESS_DATE);
CREATE INDEX IX_SALES_CLOSE_DATE ON POS_SALES_CLOSE (STORE_ID, CLOSED_AT);
CREATE INDEX IX_CLOSE_MENU_CLOSE ON POS_SALES_CLOSE_MENU (CLOSE_ID);
