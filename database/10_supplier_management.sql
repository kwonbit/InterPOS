-- InterPOS supplier management extension
-- Firebird 5.0 / UTF8
-- Run once after database/09_inventory_management.sql.
-- Do not execute this migration more than once.

CREATE TABLE POS_SUPPLIER (
  SUPPLIER_ID INTEGER NOT NULL,
  STORE_ID INTEGER NOT NULL,
  SUPPLIER_NAME VARCHAR(120) NOT NULL,
  BUSINESS_NO VARCHAR(20),
  CONTACT_NAME VARCHAR(60),
  TEL VARCHAR(30),
  EMAIL VARCHAR(120),
  ADDRESS VARCHAR(250),
  NOTE VARCHAR(500),
  ACTIVE_YN CHAR(1) DEFAULT 'Y' NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_POS_SUPPLIER PRIMARY KEY (SUPPLIER_ID),
  CONSTRAINT FK_POS_SUPPLIER_STORE FOREIGN KEY (STORE_ID)
    REFERENCES STORE_INFO(STORE_ID),
  CONSTRAINT CK_POS_SUPPLIER_ACTIVE CHECK (ACTIVE_YN IN ('Y', 'N'))
);

CREATE SEQUENCE GEN_POS_SUPPLIER_ID;

EXECUTE BLOCK
AS
  DECLARE VARIABLE V_ID INTEGER;
BEGIN
  SELECT COALESCE(MAX(SUPPLIER_ID), 0) + 1
    FROM POS_SUPPLIER INTO :V_ID;
  EXECUTE STATEMENT 'ALTER SEQUENCE GEN_POS_SUPPLIER_ID RESTART WITH ' ||
    CAST(V_ID AS VARCHAR(20));
END;

CREATE INDEX IX_POS_SUPPLIER_STORE_NAME
  ON POS_SUPPLIER (STORE_ID, SUPPLIER_NAME);
