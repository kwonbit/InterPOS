-- InterPOS purchase and receiving management
-- Firebird 5.0 / UTF8
-- Run once after database/10_supplier_management.sql.
-- Do not execute this migration more than once.

CREATE TABLE POS_PURCHASE (
  PURCHASE_ID BIGINT NOT NULL,
  STORE_ID INTEGER NOT NULL,
  SUPPLIER_ID INTEGER NOT NULL,
  PURCHASE_DATE DATE DEFAULT CURRENT_DATE NOT NULL,
  PURCHASE_STATUS VARCHAR(12) DEFAULT 'DRAFT' NOT NULL,
  TOTAL_AMOUNT NUMERIC(15,2) DEFAULT 0 NOT NULL,
  NOTE VARCHAR(500),
  CREATED_BY INTEGER NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  RECEIVED_BY INTEGER,
  RECEIVED_AT TIMESTAMP,
  CANCELLED_BY INTEGER,
  CANCELLED_AT TIMESTAMP,
  CONSTRAINT PK_POS_PURCHASE PRIMARY KEY (PURCHASE_ID),
  CONSTRAINT FK_POS_PURCHASE_STORE FOREIGN KEY (STORE_ID) REFERENCES STORE_INFO(STORE_ID),
  CONSTRAINT FK_POS_PURCHASE_SUPPLIER FOREIGN KEY (SUPPLIER_ID) REFERENCES POS_SUPPLIER(SUPPLIER_ID),
  CONSTRAINT FK_POS_PURCHASE_CREATED FOREIGN KEY (CREATED_BY) REFERENCES EMPLOYEE(EMPLOYEE_ID),
  CONSTRAINT FK_POS_PURCHASE_RECEIVED FOREIGN KEY (RECEIVED_BY) REFERENCES EMPLOYEE(EMPLOYEE_ID),
  CONSTRAINT FK_POS_PURCHASE_CANCELLED FOREIGN KEY (CANCELLED_BY) REFERENCES EMPLOYEE(EMPLOYEE_ID),
  CONSTRAINT CK_POS_PURCHASE_STATUS CHECK (PURCHASE_STATUS IN ('DRAFT', 'RECEIVED', 'CANCELLED')),
  CONSTRAINT CK_POS_PURCHASE_AMOUNT CHECK (TOTAL_AMOUNT >= 0)
);

CREATE SEQUENCE GEN_POS_PURCHASE_ID;

EXECUTE BLOCK
AS
  DECLARE VARIABLE V_ID BIGINT;
BEGIN
  SELECT COALESCE(MAX(PURCHASE_ID), 0) + 1
    FROM POS_PURCHASE INTO :V_ID;
  EXECUTE STATEMENT 'ALTER SEQUENCE GEN_POS_PURCHASE_ID RESTART WITH ' ||
    CAST(V_ID AS VARCHAR(20));
END;

CREATE TABLE POS_PURCHASE_ITEM (
  PURCHASE_ITEM_ID BIGINT NOT NULL,
  STORE_ID INTEGER NOT NULL,
  PURCHASE_ID BIGINT NOT NULL,
  MENU_ID INTEGER NOT NULL,
  QUANTITY NUMERIC(15,3) NOT NULL,
  UNIT_COST NUMERIC(15,2) NOT NULL,
  LINE_AMOUNT NUMERIC(15,2) NOT NULL,
  CONSTRAINT PK_POS_PURCHASE_ITEM PRIMARY KEY (PURCHASE_ITEM_ID),
  CONSTRAINT FK_POS_PURCHASE_ITEM_STORE FOREIGN KEY (STORE_ID) REFERENCES STORE_INFO(STORE_ID),
  CONSTRAINT FK_POS_PURCHASE_ITEM_HEADER FOREIGN KEY (PURCHASE_ID) REFERENCES POS_PURCHASE(PURCHASE_ID),
  CONSTRAINT FK_POS_PURCHASE_ITEM_MENU FOREIGN KEY (MENU_ID) REFERENCES MENU_ITEM(MENU_ID),
  CONSTRAINT CK_POS_PURCHASE_ITEM_QTY CHECK (QUANTITY > 0),
  CONSTRAINT CK_POS_PURCHASE_ITEM_COST CHECK (UNIT_COST >= 0 AND LINE_AMOUNT >= 0)
);

CREATE SEQUENCE GEN_POS_PURCHASE_ITEM_ID;

EXECUTE BLOCK
AS
  DECLARE VARIABLE V_ID BIGINT;
BEGIN
  SELECT COALESCE(MAX(PURCHASE_ITEM_ID), 0) + 1
    FROM POS_PURCHASE_ITEM INTO :V_ID;
  EXECUTE STATEMENT 'ALTER SEQUENCE GEN_POS_PURCHASE_ITEM_ID RESTART WITH ' ||
    CAST(V_ID AS VARCHAR(20));
END;

CREATE INDEX IX_POS_PURCHASE_STORE_DATE
  ON POS_PURCHASE (STORE_ID, PURCHASE_DATE, PURCHASE_STATUS);
CREATE INDEX IX_POS_PURCHASE_SUPPLIER
  ON POS_PURCHASE (STORE_ID, SUPPLIER_ID, PURCHASE_DATE);
CREATE INDEX IX_POS_PURCHASE_ITEM_HEADER
  ON POS_PURCHASE_ITEM (STORE_ID, PURCHASE_ID);
CREATE INDEX IX_POS_PURCHASE_ITEM_MENU
  ON POS_PURCHASE_ITEM (STORE_ID, MENU_ID);
