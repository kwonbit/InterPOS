CREATE TABLE POS_PURCHASE_PAYMENT (
  PAYMENT_ID BIGINT NOT NULL,
  STORE_ID INTEGER NOT NULL,
  PURCHASE_ID BIGINT NOT NULL,
  PAYMENT_DATE DATE DEFAULT CURRENT_DATE NOT NULL,
  PAYMENT_AMOUNT NUMERIC(15,2) NOT NULL,
  PAYMENT_METHOD VARCHAR(12) DEFAULT 'BANK' NOT NULL,
  NOTE VARCHAR(300),
  EMPLOYEE_ID INTEGER NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_POS_PURCHASE_PAYMENT PRIMARY KEY (PAYMENT_ID),
  CONSTRAINT FK_POS_PURCHASE_PAYMENT_STORE FOREIGN KEY (STORE_ID)
    REFERENCES STORE_INFO(STORE_ID),
  CONSTRAINT FK_POS_PURCHASE_PAYMENT_PURCHASE FOREIGN KEY (PURCHASE_ID)
    REFERENCES POS_PURCHASE(PURCHASE_ID),
  CONSTRAINT FK_POS_PURCHASE_PAYMENT_EMPLOYEE FOREIGN KEY (EMPLOYEE_ID)
    REFERENCES EMPLOYEE(EMPLOYEE_ID),
  CONSTRAINT CK_POS_PURCHASE_PAYMENT_AMOUNT CHECK (PAYMENT_AMOUNT > 0),
  CONSTRAINT CK_POS_PURCHASE_PAYMENT_METHOD CHECK
    (PAYMENT_METHOD IN ('CASH', 'BANK', 'CARD', 'OTHER'))
);

CREATE SEQUENCE GEN_POS_PURCHASE_PAYMENT_ID;

EXECUTE BLOCK
AS
  DECLARE VARIABLE V_ID BIGINT;
BEGIN
  SELECT COALESCE(MAX(PAYMENT_ID), 0) + 1
    FROM POS_PURCHASE_PAYMENT INTO :V_ID;
  EXECUTE STATEMENT 'ALTER SEQUENCE GEN_POS_PURCHASE_PAYMENT_ID RESTART WITH ' ||
    CAST(V_ID AS VARCHAR(20));
END;

CREATE INDEX IX_POS_PURCHASE_PAYMENT_PURCHASE
  ON POS_PURCHASE_PAYMENT (STORE_ID, PURCHASE_ID, PAYMENT_DATE);
