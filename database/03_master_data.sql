-- InterPOS master-data extension for Firebird 5.0
-- Run once against an existing InterPOS database after 01_schema.sql.

ALTER TABLE MENU_ITEM ADD DESCRIPTION VARCHAR(500);
ALTER TABLE MENU_ITEM ADD DISPLAY_ORDER INTEGER DEFAULT 0 NOT NULL;

CREATE TABLE MENU_OPTION_GROUP (
  OPTION_GROUP_ID INTEGER NOT NULL,
  STORE_ID INTEGER NOT NULL,
  GROUP_NAME VARCHAR(80) NOT NULL,
  REQUIRED_YN CHAR(1) DEFAULT 'N' NOT NULL,
  MAX_SELECT INTEGER DEFAULT 1 NOT NULL,
  DISPLAY_ORDER INTEGER DEFAULT 0 NOT NULL,
  ACTIVE_YN CHAR(1) DEFAULT 'Y' NOT NULL,
  CONSTRAINT PK_MENU_OPTION_GROUP PRIMARY KEY (OPTION_GROUP_ID),
  CONSTRAINT FK_OPTION_GROUP_STORE FOREIGN KEY (STORE_ID) REFERENCES STORE_INFO(STORE_ID)
);

CREATE TABLE MENU_OPTION (
  OPTION_ID INTEGER NOT NULL,
  OPTION_GROUP_ID INTEGER NOT NULL,
  OPTION_NAME VARCHAR(100) NOT NULL,
  ADD_PRICE NUMERIC(15,2) DEFAULT 0 NOT NULL,
  DISPLAY_ORDER INTEGER DEFAULT 0 NOT NULL,
  ACTIVE_YN CHAR(1) DEFAULT 'Y' NOT NULL,
  CONSTRAINT PK_MENU_OPTION PRIMARY KEY (OPTION_ID),
  CONSTRAINT FK_OPTION_GROUP FOREIGN KEY (OPTION_GROUP_ID)
    REFERENCES MENU_OPTION_GROUP(OPTION_GROUP_ID)
);

CREATE TABLE MENU_ITEM_OPTION_GROUP (
  MENU_ID INTEGER NOT NULL,
  OPTION_GROUP_ID INTEGER NOT NULL,
  DISPLAY_ORDER INTEGER DEFAULT 0 NOT NULL,
  CONSTRAINT PK_MENU_ITEM_OPTION_GROUP PRIMARY KEY (MENU_ID, OPTION_GROUP_ID),
  CONSTRAINT FK_MIOG_MENU FOREIGN KEY (MENU_ID) REFERENCES MENU_ITEM(MENU_ID),
  CONSTRAINT FK_MIOG_GROUP FOREIGN KEY (OPTION_GROUP_ID)
    REFERENCES MENU_OPTION_GROUP(OPTION_GROUP_ID)
);

CREATE UNIQUE INDEX UX_POS_TABLE_STORE_NAME ON POS_TABLE (STORE_ID, TABLE_NAME);
CREATE UNIQUE INDEX UX_MENU_CATEGORY_STORE_NAME ON MENU_CATEGORY (STORE_ID, CATEGORY_NAME);
CREATE UNIQUE INDEX UX_MENU_ITEM_STORE_NAME ON MENU_ITEM (STORE_ID, MENU_NAME);
CREATE INDEX IX_MENU_ITEM_CATEGORY ON MENU_ITEM (STORE_ID, CATEGORY_ID, DISPLAY_ORDER);
CREATE INDEX IX_OPTION_GROUP_STORE ON MENU_OPTION_GROUP (STORE_ID, DISPLAY_ORDER);
CREATE INDEX IX_MENU_OPTION_GROUP ON MENU_OPTION (OPTION_GROUP_ID, DISPLAY_ORDER);
