-- InterPOS ingredient stocktaking and adjustment history
-- Firebird 5.0 / UTF8. Run once after migration 17.

CREATE TABLE POS_INGREDIENT_STOCKTAKE (
  STOCKTAKE_ID BIGINT NOT NULL,
  STORE_ID INTEGER NOT NULL,
  INGREDIENT_ID BIGINT NOT NULL,
  BOOK_QTY NUMERIC(15,3) NOT NULL,
  COUNTED_QTY NUMERIC(15,3) NOT NULL,
  DIFFERENCE_QTY NUMERIC(15,3) NOT NULL,
  REASON VARCHAR(250) NOT NULL,
  EMPLOYEE_ID INTEGER NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_POS_ING_STOCKTAKE PRIMARY KEY (STOCKTAKE_ID),
  CONSTRAINT FK_POS_ING_STK_STORE FOREIGN KEY (STORE_ID) REFERENCES STORE_INFO(STORE_ID),
  CONSTRAINT FK_POS_ING_STK_ING FOREIGN KEY (INGREDIENT_ID) REFERENCES POS_INGREDIENT(INGREDIENT_ID),
  CONSTRAINT FK_POS_ING_STK_EMP FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEE(EMPLOYEE_ID)
);

CREATE SEQUENCE GEN_POS_ING_STOCKTAKE_ID;
EXECUTE BLOCK
AS
  DECLARE VARIABLE V_ID BIGINT;
BEGIN
  SELECT COALESCE(MAX(STOCKTAKE_ID), 0) + 1
    FROM POS_INGREDIENT_STOCKTAKE INTO :V_ID;
  EXECUTE STATEMENT 'ALTER SEQUENCE GEN_POS_ING_STOCKTAKE_ID RESTART WITH ' ||
    CAST(V_ID AS VARCHAR(20));
END;

CREATE INDEX IX_POS_ING_STOCKTAKE_DATE
  ON POS_INGREDIENT_STOCKTAKE (STORE_ID, CREATED_AT);
CREATE INDEX IX_POS_ING_STOCKTAKE_ING
  ON POS_INGREDIENT_STOCKTAKE (STORE_ID, INGREDIENT_ID, CREATED_AT);
