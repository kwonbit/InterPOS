-- InterPOS ingredient purchasing and receiving
-- Firebird 5.0 / UTF8
-- Run once after database/14_ingredient_recipe_management.sql.
-- Do not execute this migration more than once.
--
-- Ingredient purchase lines share POS_PURCHASE headers so supplier payable
-- registration and payment history continue to work without changing them.

CREATE TABLE POS_INGREDIENT_PURCHASE_ITEM (
  INGREDIENT_PURCHASE_ITEM_ID BIGINT NOT NULL,
  STORE_ID INTEGER NOT NULL,
  PURCHASE_ID BIGINT NOT NULL,
  INGREDIENT_ID BIGINT NOT NULL,
  QUANTITY NUMERIC(15,3) NOT NULL,
  UNIT_COST NUMERIC(15,4) NOT NULL,
  LINE_AMOUNT NUMERIC(15,2) NOT NULL,
  CONSTRAINT PK_POS_ING_PURCHASE_ITEM PRIMARY KEY (INGREDIENT_PURCHASE_ITEM_ID),
  CONSTRAINT FK_POS_ING_PURCHASE_STORE FOREIGN KEY (STORE_ID) REFERENCES STORE_INFO(STORE_ID),
  CONSTRAINT FK_POS_ING_PURCHASE_HEADER FOREIGN KEY (PURCHASE_ID) REFERENCES POS_PURCHASE(PURCHASE_ID),
  CONSTRAINT FK_POS_ING_PURCHASE_ING FOREIGN KEY (INGREDIENT_ID) REFERENCES POS_INGREDIENT(INGREDIENT_ID),
  CONSTRAINT CK_POS_ING_PURCHASE_QTY CHECK (QUANTITY > 0),
  CONSTRAINT CK_POS_ING_PURCHASE_COST CHECK (UNIT_COST >= 0 AND LINE_AMOUNT >= 0)
);

CREATE SEQUENCE GEN_POS_ING_PURCHASE_ITEM_ID;
EXECUTE BLOCK
AS
  DECLARE VARIABLE V_ID BIGINT;
BEGIN
  SELECT COALESCE(MAX(INGREDIENT_PURCHASE_ITEM_ID), 0) + 1
    FROM POS_INGREDIENT_PURCHASE_ITEM INTO :V_ID;
  EXECUTE STATEMENT 'ALTER SEQUENCE GEN_POS_ING_PURCHASE_ITEM_ID RESTART WITH ' ||
    CAST(V_ID AS VARCHAR(20));
END;

CREATE INDEX IX_POS_ING_PURCHASE_HEADER
  ON POS_INGREDIENT_PURCHASE_ITEM (STORE_ID, PURCHASE_ID);
CREATE INDEX IX_POS_ING_PURCHASE_ING
  ON POS_INGREDIENT_PURCHASE_ITEM (STORE_ID, INGREDIENT_ID);
